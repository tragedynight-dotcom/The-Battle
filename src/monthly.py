CASE_RE = re.compile(
    r"(?:대법원|고등법원|지방법원|수원지법|의정부지법)[^\d]{0,8}"
    r"(\d{2,4}\s*[도모누카합아고정다]+\s*\d+)"
    r"|(\d{4}\s*[도모누카합아다]\s*\d+)"
    r"|(\d{2,4}[도모누카합아다]\d{2,})"
)


def cites_from_area(area: dict | None, limit: int = 8) -> list[str]:
    if not area:
        return []
    text = "\n".join((it.get("src") or "") + "\n" + (it.get("exp") or "") for it in area["items"])
    found: list[str] = []
    seen: set[str] = set()
    for m in CASE_RE.finditer(text):
        raw = next((g for g in m.groups() if g), "")
        key = re.sub(r"\s+", "", raw)
        if len(key) < 6 or key in seen:
            continue
        seen.add(key)
        found.append(key)
        if len(found) >= limit:
            break
    return found


def pack_for(month: int) -> dict:
    for p in PACKS:
        if p["month"] == month:
            return p
    return PACKS[0]


def pick_items(area: dict, year: int, month: int, n: int = 5) -> list[dict]:
    items = list(area["items"])
    rng = random.Random(f"{year}-{month:02d}-{area['id']}")
    k = min(n, len(items))
    chosen = rng.sample(items, k=k)
    out = []
    for it in chosen:
        row = dict(it)
        row["area"] = area["name"]
        row["area_id"] = area["id"]
        out.append(row)
    return out


def area_by_name(areas: list[dict], name: str) -> dict | None:
    for a in areas:
        if a["name"] == name:
            return a
    return None


def this_month() -> int:
    return date.today().month
